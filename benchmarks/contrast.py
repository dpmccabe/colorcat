"""Show the README's ``palette(5)`` at several ``min_contrast`` values.

Writes ``benchmarks/contrast.md`` and one SVG per background (``contrast_white.svg``,
``contrast_black.svg``) showing the 5-color palette with ``min_contrast`` 1.5, 2, 3
(the default, the saved palette in the README) and 4.5, with the closest-pair
distance and the lowest contrast ratio actually reached.
Non-default values run the optimizer with ``restart_count=20``, as the saved
palettes did.

    uv run python benchmarks/contrast.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from colorcat import min_distance, palette
from colorcat._format import hex_to_srgb
from colorcat._oklab import contrast_ratio, relative_luminance, srgb_to_linear

N = 5
RATIOS = (1.2, 2.0, 3.0, 4.5)
BACKGROUNDS = ("white", "black")
RESTART_COUNT = 20
HERE = Path(__file__).parent
OUT = HERE / "contrast.md"
SW, GAP, PAD, ROW, LABEL, STATS = 40, 6, 16, 56, 120, 150
THEME = {"white": ("#ffffff", "#222"), "black": ("#000000", "#eee")}


def lowest_contrast(colors: list[str], background: str) -> float:
    y = relative_luminance(srgb_to_linear(np.array([hex_to_srgb(c) for c in colors])))
    return float(contrast_ratio(y, 1.0 if background == "white" else 0.0).min())


def svg(background: str, rows: list[tuple[float, list[str], float, float]]) -> str:
    bg, fg = THEME[background]
    width = LABEL + N * (SW + GAP) + STATS + PAD
    height = PAD * 2 + ROW * len(rows)
    font = 'font-family="system-ui, sans-serif"'
    out = [
        (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
            f'width="{width}" height="{height}">'
        ),
        f'<rect width="{width}" height="{height}" fill="{bg}"/>',
    ]
    for i, (ratio, colors, dist, contrast) in enumerate(rows):
        y = PAD + i * ROW
        out.append(
            f'<text x="{PAD}" y="{y + 28}" fill="{fg}" font-size="13" {font}>'
            f"min_contrast {ratio:g}</text>"
        )
        for j, c in enumerate(colors):
            out.append(
                f'<rect x="{LABEL + j * (SW + GAP)}" y="{y + 4}" width="{SW}" height="{SW + 8}" '
                f'rx="4" fill="{c}"><title>{c}</title></rect>'
            )
        x = LABEL + N * (SW + GAP) + 10
        out.append(
            f'<text x="{x}" y="{y + 22}" fill="{fg}" font-size="12" {font}>min ΔE {dist:.3f}</text>'
            f'<text x="{x}" y="{y + 40}" fill="{fg}" opacity="0.6" font-size="11" {font}>'
            f"contrast ≥ {contrast:.2f}</text>"
        )
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main() -> None:
    lines = [
        f"# `palette({N})` by `min_contrast`",
        "",
        (
            "Generated by `benchmarks/contrast.py`. `min ΔE` is the distance between the closest "
            "pair of colors (ΔE_OK, higher is better); `contrast` is the smallest WCAG contrast "
            "ratio between a color and the background. The default is `min_contrast=3`."
        ),
    ]
    for background in BACKGROUNDS:
        rows = []
        for ratio in RATIOS:
            if ratio == 3.0:
                colors = palette(N, background=background)  # the saved palette
            else:
                colors = palette(
                    N, background=background, min_contrast=ratio, restart_count=RESTART_COUNT
                )
            rows.append((ratio, colors, min_distance(colors), lowest_contrast(colors, background)))
            print(background, ratio, colors)
        name = f"contrast_{background}.svg"
        (HERE / name).write_text(svg(background, rows))
        lines += ["", f"## {background.capitalize()} background", "", f"![{background}]({name})"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
